// Package pi emits a Pi coding-agent TypeScript provider extension.
package pi

import (
	"fmt"
	"strings"

	"agentcfg/internal/artifact"
	"agentcfg/internal/diag"
	"agentcfg/internal/ir"
	"agentcfg/internal/target"
)

func init() { target.Register(Target{}) }

// Target is the Pi emitter.
type Target struct{}

func (Target) ID() string { return "pi" }

func (t Target) Validate(cfg ir.Config) []diag.Diagnostic {
	var diags []diag.Diagnostic
	if len(cfg.MCP) > 0 {
		diags = append(diags, diag.TargetErrorf(t.ID(), "mcp",
			"pi has no built-in MCP support; the pi-mcp-adapter is a third-party dependency and is not generated by v1"))
	}
	return diags
}

func (t Target) Emit(cfg ir.Config) ([]artifact.Artifact, error) {
	var b strings.Builder
	b.WriteString("// Generated by agentcfg. Do not edit.\n")
	b.WriteString("// Install: copy to ~/.pi/agent/extensions/ and restart pi.\n")
	b.WriteString("\nexport default function (pi: any) {\n")
	for _, p := range cfg.Providers {
		fmt.Fprintf(&b, "  pi.registerProvider({\n")
		fmt.Fprintf(&b, "    id: %q,\n", p.ID)
		fmt.Fprintf(&b, "    name: %q,\n", orDefault(p.Name, p.ID))
		fmt.Fprintf(&b, "    api: %q,\n", string(p.Protocol))
		fmt.Fprintf(&b, "    baseUrl: %q,\n", p.BaseURL)
		if p.APIKeyEnv != "" {
			fmt.Fprintf(&b, "    apiKey: \"$%s\",\n", p.APIKeyEnv)
		} else {
			b.WriteString("    apiKey: \"\",\n")
		}
		b.WriteString("    models: [\n")
		for _, m := range p.Models {
			in := m.Input
			if len(in) == 0 {
				in = []ir.Modality{ir.ModalityText}
			}
			modIn := make([]string, 0, len(in))
			for _, x := range in {
				modIn = append(modIn, fmt.Sprintf("%q", string(x)))
			}
			fmt.Fprintf(&b, "      {\n")
			fmt.Fprintf(&b, "        id: %q,\n", m.ID)
			fmt.Fprintf(&b, "        name: %q,\n", orDefault(m.Name, m.ID))
			fmt.Fprintf(&b, "        input: [%s],\n", strings.Join(modIn, ", "))
			fmt.Fprintf(&b, "        reasoning: %s,\n", boolJS(m.Reasoning))
			fmt.Fprintf(&b, "        cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },\n")
			if m.ContextWindow != nil {
				fmt.Fprintf(&b, "        contextWindow: %d,\n", *m.ContextWindow)
			} else {
				b.WriteString("        contextWindow: 0,\n")
			}
			if m.MaxOutputTokens != nil {
				fmt.Fprintf(&b, "        maxTokens: %d,\n", *m.MaxOutputTokens)
			} else {
				b.WriteString("        maxTokens: 0,\n")
			}
			b.WriteString("      },\n")
		}
		b.WriteString("    ],\n")
		b.WriteString("  });\n")
	}
	b.WriteString("}\n")

	return []artifact.Artifact{{
		Target:        t.ID(),
		Name:          "agentcfg-providers.ts",
		Format:        "typescript",
		SuggestedPath: "~/.pi/agent/extensions/agentcfg-providers.ts",
		Content:       []byte(b.String()),
	}}, nil
}

func boolJS(b *bool) string {
	if b != nil && *b {
		return "true"
	}
	return "false"
}

func orDefault(v, def string) string {
	if v == "" {
		return def
	}
	return v
}
