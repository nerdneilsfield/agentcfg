// Package pi emits a Pi coding-agent TypeScript provider extension.
package pi

import (
	"fmt"
	"sort"
	"strings"

	"agentcfg/internal/artifact"
	"agentcfg/internal/diag"
	"agentcfg/internal/ir"
	"agentcfg/internal/target"
)

func init() { target.Register(Target{}) }

// Target is the Pi emitter.
type Target struct{}

func (Target) ID() string { return "pi" }

func (t Target) Validate(cfg ir.Config) []diag.Diagnostic {
	var diags []diag.Diagnostic
	for i, p := range cfg.Providers {
		if strings.HasPrefix(p.APIKey.Value, "$") || strings.HasPrefix(p.APIKey.Value, "!") {
			diags = append(diags, diag.TargetErrorf(t.ID(), fmt.Sprintf("providers[%d].api_key", i), "literal API key contains native expression syntax and cannot be represented literally"))
		}
	}
	for i, p := range cfg.Providers {
		for name, v := range p.Headers {
			if v.BearerFromEnv != "" {
				diags = append(diags, diag.TargetErrorf(t.ID(), fmt.Sprintf("providers[%d].headers.%s", i, name),
					"pi header values use the $NAME expression syntax; Bearer ENV:NAME has no verified bearer expansion and is rejected"))
			}
		}
	}
	if len(cfg.MCP) > 0 {
		diags = append(diags, diag.TargetErrorf(t.ID(), "mcp",
			"pi has no built-in MCP support; the pi-mcp-adapter is a third-party dependency and is not generated by v1"))
	}
	return diags
}

func (t Target) Emit(cfg ir.Config) ([]artifact.Artifact, error) {
	var b strings.Builder
	b.WriteString("// Generated by agentcfg. Do not edit.\n")
	b.WriteString("// Install: copy to ~/.pi/agent/extensions/ and restart pi.\n")
	b.WriteString("\nexport default function (pi: any) {\n")
	for _, p := range cfg.Providers {
		fmt.Fprintf(&b, "  pi.registerProvider({\n")
		fmt.Fprintf(&b, "    id: %q,\n", p.ID)
		fmt.Fprintf(&b, "    name: %q,\n", orDefault(p.Name, p.ID))
		fmt.Fprintf(&b, "    api: %q,\n", string(p.Protocol))
		fmt.Fprintf(&b, "    baseUrl: %q,\n", p.BaseURL)
		if p.APIKey.FromEnv != "" {
			fmt.Fprintf(&b, "    apiKey: \"$%s\",\n", p.APIKey.FromEnv)
		} else if p.APIKey.Value != "" {
			fmt.Fprintf(&b, "    apiKey: %q,\n", p.APIKey.Value)
		} else {
			b.WriteString("    apiKey: \"\",\n")
		}
		if len(p.Headers) > 0 {
			b.WriteString("    headers: {\n")
			for _, name := range sortedHeaderNames(p.Headers) {
				v := p.Headers[name]
				if v.FromEnv != "" {
					fmt.Fprintf(&b, "      %q: \"$%s\",\n", name, v.FromEnv)
				} else {
					fmt.Fprintf(&b, "      %q: %q,\n", name, v.Value)
				}
			}
			b.WriteString("    },\n")
		}
		b.WriteString("    models: [\n")
		for _, m := range p.Models {
			in := m.Input
			if len(in) == 0 {
				in = []ir.Modality{ir.ModalityText}
			}
			modIn := make([]string, 0, len(in))
			for _, x := range in {
				modIn = append(modIn, fmt.Sprintf("%q", string(x)))
			}
			fmt.Fprintf(&b, "      {\n")
			fmt.Fprintf(&b, "        id: %q,\n", m.ID)
			fmt.Fprintf(&b, "        name: %q,\n", orDefault(m.Name, m.ID))
			fmt.Fprintf(&b, "        input: [%s],\n", strings.Join(modIn, ", "))
			fmt.Fprintf(&b, "        reasoning: %s,\n", boolJS(m.Reasoning))
			if hasPiThinkingLevels(m.Variants) {
				b.WriteString("        thinkingLevelMap: {\n")
				for _, level := range piThinkingLevels {
					if containsEffort(m.Variants, level) {
						fmt.Fprintf(&b, "          %q: %q,\n", level, level)
					} else {
						fmt.Fprintf(&b, "          %q: null,\n", level)
					}
				}
				b.WriteString("        },\n")
			}
			fmt.Fprintf(&b, "        cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },\n")
			if m.ContextWindow != nil {
				fmt.Fprintf(&b, "        contextWindow: %d,\n", *m.ContextWindow)
			} else {
				b.WriteString("        contextWindow: 0,\n")
			}
			if m.MaxOutputTokens != nil {
				fmt.Fprintf(&b, "        maxTokens: %d,\n", *m.MaxOutputTokens)
			} else {
				b.WriteString("        maxTokens: 0,\n")
			}
			b.WriteString("      },\n")
		}
		b.WriteString("    ],\n")
		b.WriteString("  });\n")
	}
	b.WriteString("}\n")

	return []artifact.Artifact{{
		Target:        t.ID(),
		Name:          "agentcfg-providers.ts",
		Format:        "typescript",
		SuggestedPath: "~/.pi/agent/extensions/agentcfg-providers.ts",
		Content:       []byte(b.String()),
	}}, nil
}

func boolJS(b *bool) string {
	if b != nil && *b {
		return "true"
	}
	return "false"
}

func orDefault(v, def string) string {
	if v == "" {
		return def
	}
	return v
}

var piThinkingLevels = []ir.ReasoningEffort{"off", "minimal", "low", "medium", "high", "xhigh", "max"}

func piThinkingLevel(effort ir.ReasoningEffort) bool { return containsEffort(piThinkingLevels, effort) }
func hasPiThinkingLevels(efforts []ir.ReasoningEffort) bool {
	for _, effort := range efforts {
		if piThinkingLevel(effort) {
			return true
		}
	}
	return false
}

func containsEffort(efforts []ir.ReasoningEffort, wanted ir.ReasoningEffort) bool {
	for _, effort := range efforts {
		if effort == wanted {
			return true
		}
	}
	return false
}

func sortedHeaderNames(headers map[string]ir.HeaderValue) []string {
	names := make([]string, 0, len(headers))
	for name := range headers {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
